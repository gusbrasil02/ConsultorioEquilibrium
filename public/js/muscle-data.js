export const MUSCLE_INDEX = new Map(MUSCLES.map((m, i) => [m.key, i]))

// id no mapa de músculos (lado: 'D' = direito, 'E' = esquerdo)
export function muscleId(key, side) {
  const i = MUSCLE_INDEX.get(key)
  return i == null ? 0 : 1 + 2 * i + (side === 'E' ? 1 : 0)
}
// id → { muscle, side }
export function muscleFromId(id) {
  if (!id) return null
  const i = (id - 1) >> 1
  const m = MUSCLES[i]
  return m ? { muscle: m, side: (id - 1) % 2 ? 'E' : 'D' } : null
}
export function findMuscle(key) { const i = MUSCLE_INDEX.get(key); return i == null ? null : MUSCLES[i] }
